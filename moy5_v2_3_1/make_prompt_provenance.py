#!/usr/bin/env python3
"""make_prompt_provenance.py — cards/PROMPT_PROVENANCE.md: where the question texts of the moy-5 figure come from, with md5 at each stage.

Inputs (all inside this bundle; nothing is imported or run from ConstructGap or from the experiment scripts):
  data/conversations/2026-10-14/SOURCE_frozen_prompts_moy1_moy2_moy5_blocks_alt2_lines_dfc_v1_20261014.md   the frozen moy-5 question (block `parabola_section`)
  generated/pack.json                     the sentences the arms add (read from the PREREGs / SOURCE / the b5bp runner's text by pack_data.py)
  data/ConstructGap/exp/results_*.jsonl   the prompt_md5 every row recorded (what the model received)
  cards/public_constructgap_v1_0_1_text.json   the text of the public ConstructGap v1.0.1 prompts.py (read as text)
Method: the question is cut out of the SOURCE exactly as pack_data.py does; then simple compositions (question or its Q2 variant, optionally one added sentence before it, + up to three of the
added sentences after it, appended with "", "\\n" or "\\n\\n" between, with or without a final "\\n") are hashed and compared with the prompt_md5 of every arm.
An arm whose md5 no simple composition reaches is listed as NOT REBUILT (its runner composes it in code that this bundle does not run).

    python3 -I make_prompt_provenance.py        (exit 1 if the frozen question's md5 is not ee39ba02…)
"""
import collections
import glob
import hashlib
import itertools
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "data/conversations/2026-10-14/SOURCE_frozen_prompts_moy1_moy2_moy5_blocks_alt2_lines_dfc_v1_20261014.md"
md5 = lambda s: hashlib.md5(s.encode()).hexdigest()


def main() -> int:
    lines = SRC.read_text(encoding="utf-8").splitlines()
    i0 = next(i for i, l in enumerate(lines) if l.startswith("## moy-5 `parabola_section`"))
    b0 = lines.index("```", i0) + 1
    b1 = lines.index("```", b0)
    Q = "\n".join(lines[b0:b1]) + "\n"
    if not md5(Q).startswith("ee39ba02"):
        print("the frozen moy-5 question read from the SOURCE is not ee39ba02…:", md5(Q)); return 1
    S = json.loads((HERE / "generated" / "pack.json").read_text(encoding="utf-8"))["sentences"]
    Q2 = Q.replace(S["focus_q1"], S["focus_q2"])
    parts = {k: S[k] for k in ("beta", "proof", "block", "form", "conf", "khint")}
    # every arm's recorded prompt_md5
    seen = collections.defaultdict(lambda: collections.Counter())
    for f in sorted(glob.glob(str(HERE / "data/ConstructGap/exp/results_*.jsonl"))):
        card = pathlib.Path(f).name.split("_")[1]
        for l in open(f, encoding="utf-8"):
            if l.strip():
                r = json.loads(l)
                if r.get("prompt_md5"):
                    seen[r["prompt_md5"]][f"{card} {r.get('arm') or '(one arm)'}"] += 1
    # simple compositions
    cand = {md5(Q): "Q (the frozen question, SOURCE 10-14)", md5(Q2): "Q2 = Q with the focus line replaced ({E, J, K, P_y} → {F, V, P_x, P_y})"}
    joins = ["", "\n", "\n\n"]
    for base_name, base in (("Q", Q), ("Q2", Q2)):
        for pre in [None] + list(parts):                                  # one sentence before the question (e.g. "In the configuration below …"), or none
            for pj in (joins if pre else [""]):
                b = (parts[pre] + pj + base) if pre else base
                bn = (f"{pre} + {pj!r} + " if pre else "") + base_name
                for n in (0, 1, 2, 3):
                    for seq in itertools.permutations([k for k in parts if k != pre], n):
                        for js in itertools.product(joins, repeat=n):
                            for tail in ("", "\n"):
                                t = b
                                for j, k in zip(js, seq):
                                    t = t + j + parts[k]
                                t += tail
                                desc = bn + "".join(f" + {j!r} + {k}" for j, k in zip(js, seq)) + (f" + {tail!r}" if tail else "")
                                cand.setdefault(md5(t), desc)
    rows = []
    for h, arms in sorted(seen.items(), key=lambda kv: -sum(kv[1].values())):
        rows.append((h, ", ".join(f"{a} ({n})" for a, n in sorted(arms.items())), cand.get(h)))
    pub = json.loads((HERE / "cards" / "public_constructgap_v1_0_1_text.json").read_text(encoding="utf-8"))
    ptxt = pub["prompts_py_text"]
    qlines = [l for l in Q.splitlines() if l.strip()]
    inpub = [l for l in qlines if l in ptxt]
    out = ["# PROMPT_PROVENANCE — the question texts of the moy-5 figure (generated by `make_prompt_provenance.py`; do not edit by hand)", "",
           "## 1. The frozen question", "",
           f"- Source: `data/conversations/2026-10-14/SOURCE_frozen_prompts_moy1_moy2_moy5_blocks_alt2_lines_dfc_v1_20261014.md`, the code block under `## moy-5 \\`parabola_section\\`` (the same cut as `pack_data.py`).",
           f"- {len(Q)} characters (the md5 includes the final newline): md5 **`{md5(Q)}`** (frozen prefix `ee39ba02` ✓). Q2 (focus line replaced as in PREREG neq3 l.22): `{md5(Q2)}`.",
           f"- Public ConstructGap **{pub['tag']}** (`prompts.py` md5 `{pub['files']['prompts.py']}`, read as text): {len(inpub)} of the question's {len(qlines)} non-empty lines occur verbatim in `prompts.py`. "
           "The rest are built by code (coordinates and labels computed by the suite's geometry), so the question **cannot be rebuilt from the public repository without running it**; this bundle does not run it — the frozen text in the SOURCE is the reference, and the rows' `prompt_md5` agree with it (below).", "",
           "```", Q.rstrip("\n"), "```", "",
           "## 2. What each arm received (prompt_md5 of the rows) and how far a simple composition reaches it", "",
           "Compositions tried: Q or Q2, optionally one added sentence before it, plus up to three of the added sentences after it (`beta` = β′ of b5bp, `proof` = PROOF of prf1, `block` = the block of prf2 / prf3, `form` = the proportion note of mnw1, "
           "`conf` = the Newton roles of mnw1, `khint` = the positive-control hint K), joined with \"\", \"\\n\" or \"\\n\\n\", with or without a final \"\\n\". "
           "The sentences are the pack's (`generated/pack.json` → `sentences`). NOT REBUILT = no such composition gives the md5 (the runner builds that text in code that is not run here; mnw1's `cone` text is a 926-character paragraph of which the pack keeps only the Japanese gist).", "",
           "| prompt_md5 | card · arm (rows) | rebuilt as |", "|---|---|---|"]
    for h, arms, how in rows:
        out.append(f"| `{h}` | {arms} | {('`' + how.replace('|', '/') + '`') if how else '**NOT REBUILT**'} |")
    n_ok = sum(1 for r in rows if r[2])
    out += ["", f"Rebuilt {n_ok} of {len(rows)} distinct prompt texts; the md5 values are the rows' own records (R4: the evidence is the output).", "",
            "## 3. The added sentences (verbatim, from the pack)", ""]
    for k, v in S.items():
        out.append(f"- `{k}` (md5 `{md5(v)}`): {v}")
    (HERE / "cards" / "PROMPT_PROVENANCE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"PROMPT_PROVENANCE: question {md5(Q)[:8]} ({len(Q)} chars) · {len(inpub)} / {len(qlines)} lines in public prompts.py · rebuilt {n_ok} / {len(rows)} prompt texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
