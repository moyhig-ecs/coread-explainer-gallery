#!/usr/bin/env python3
"""make_prompt_provenance.py — cards/PROMPT_PROVENANCE.md: where the question text of the moy-2 cards comes from, with md5 at each stage.

Inputs (all inside this bundle):
  cards/prompt_higashida_axis_A_37_v1_0_1.json   prompts.build("higashida_axis", "A", 37) of the public ConstructGap (tag v1.0.1)
  data/moy2_line_inventory.json                  the Tool sections (verbatim) and the frozen prompt md5 of olm122/124 and olm125/127
  the constants below                            copied verbatim from the frozen house script (hq_moy12_status_proof_common_20261102.py;
                                                 the script itself is not in the bundle and is neither imported nor run)
Chain:  public prompt --F5a-2 edit--> M2 --+ APPEND_M2--> M2A --+ Tool section at char 777 (after "Premises")--> olm119 / olm122,124 / olm125,127
        OLMo received text + CUE ("\\n\\n"); the frozen md5 values include the CUE.

    python3 -I make_prompt_provenance.py        (asserts every frozen md5 it can find in the bundle; exit 1 on any mismatch)
"""
import hashlib
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
CARDS = HERE / "cards"
md5 = lambda s: hashlib.md5(s.encode()).hexdigest()

# --- constants, verbatim from the frozen house script (lines 34–47) ---------------------------------------------
CUE = "\n\n"
F5A2_EDIT = ("Respond with JSON only:", "First write your reasoning as plain text.\nAfter that, respond with the JSON object:")
APPEND_M2 = ("\nThen answer two more questions about your invariant. "
             "(1) Is it a HYPOTHESIS or a QUESTION? "
             "(2) Give its backing: a proof that it holds. "
             "Add two fields to the JSON object: \"status\": \"hypothesis\" or \"question\", and \"proof\": \"<the proof>\".")
TOOL_AT = 777   # the Tool section is inserted right after the Premises paragraph (char 777 of M2A)


def main() -> int:
    pub = json.loads((CARDS / "prompt_higashida_axis_A_37_v1_0_1.json").read_text(encoding="utf-8"))
    inv = json.loads((HERE / "data" / "moy2_line_inventory.json").read_text(encoding="utf-8"))
    P = inv["prompts"]
    TOOL_D, TOOL_U, TOOL = P["TOOL_D(式だけ・olm122/124)"], P["TOOL_U(指示の文・olm125/127)"], P["TOOL(式 + 宣言の文・olm119)"]
    base = pub["prompt"]
    assert md5(base) == pub["_source"]["prompt_md5"], "public prompt md5 drifted"
    assert base.count(F5A2_EDIT[0]) == 1
    M2 = base.replace(F5A2_EDIT[0], F5A2_EDIT[1], 1)
    M2A = M2 + APPEND_M2
    assert M2A[TOOL_AT - 1] == "\n" and M2A[:TOOL_AT].rstrip().endswith("(non-degenerate)."), M2A[TOOL_AT - 80:TOOL_AT]
    ins = lambda tool: M2A[:TOOL_AT] + tool + M2A[TOOL_AT:] + CUE
    stages = [
        ("public prompt", "prompts.build('higashida_axis', 'A', 37)['prompt'] (ConstructGap tag v1.0.1)", base, pub["_source"]["prompt_md5"], "cards/prompt_higashida_axis_A_37_v1_0_1.json"),
        ("M2", "F5a-2 edit: 'Respond with JSON only:' → 'First write your reasoning as plain text.\\nAfter that, respond with the JSON object:'", M2, None, "—"),
        ("M2 + CUE", "what OLMo received in the M2 arm (olm113)", M2 + CUE, None, "house gen.json of olm113 (not in the bundle): ddf4ba07…"),
        ("M2A + CUE", "M2 + APPEND_M2 (+ CUE) = the olm113 'tool-less' question", M2A + CUE, None, "cards/PREREG_olm113 (quoted there as the md5 of the question; the audit notes it is M2A, not APPEND_M2 alone)"),
        ("APPEND_M2 alone", "the status / proof appendix", APPEND_M2, None, "—"),
        ("olm119", "M2A with TOOL (formula + declaration) inserted at char 777, + CUE", ins(TOOL), None, "house gen.json of olm119 (not in the bundle): d4c07f24…"),
        ("olm122 / olm124", "M2A with TOOL_D (formula only) at 777, + CUE", ins(TOOL_D), P["prompt_md5"]["olm122/124"], "data/moy2_line_inventory.json prompts.prompt_md5"),
        ("olm125 / olm127", "M2A with TOOL_D + TOOL_U (formula + 'Use it to check…') at 777, + CUE", ins(TOOL_D + TOOL_U), P["prompt_md5"]["olm125/127"], "data/moy2_line_inventory.json prompts.prompt_md5"),
    ]
    rows, bad = [], 0
    for name, how, text, expect, where in stages:
        got = md5(text)
        ok = "" if expect is None else ("✓" if got == expect else "✗")
        if ok == "✗": bad += 1
        rows.append((name, how, len(text), got, ok, where))
    # frozen strings quoted inside the cards (presence check, so the reader can grep them)
    quoted = {}
    for key, pat in [("M2A+CUE in PREREG_olm113", "56182280"), ("olm125/127 in RECORD §1", "718d1601"), ("olm122/124 in PREREG_olm124", "2c4a01a4")]:
        files = [p.name for p in sorted(CARDS.glob("*.md")) if pat in p.read_text(encoding="utf-8")]
        quoted[key] = files
    md = ["# PROMPT_PROVENANCE — where the question text of the moy-2 cards comes from", "",
          "Generated by `make_prompt_provenance.py` from files inside this bundle (the public ConstructGap prompt, the inventory's Tool sections) and the constants "
          "copied verbatim from the frozen house script. Every md5 is of the UTF-8 text; the frozen values include the trailing CUE (`\\n\\n`) that OLMo received.", "",
          "| stage | how | chars | md5 | frozen? | where the frozen value is written |", "|---|---|---:|---|:-:|---|"]
    md += [f"| {n} | {h} | {c} | `{m}` | {o} | {w} |" for n, h, c, m, o, w in rows]
    md += ["", f"- source of the public prompt: {pub['_source']['repo']} tag `{pub['_source']['tag']}`, `prompts.py` md5 `{pub['_source']['prompts_py_md5']}`, call `{pub['_source']['call']}`.",
           f"- the Tool section goes in at char {TOOL_AT} of M2A, right after the Premises paragraph (`…(non-degenerate).\\n`).",
           "- md5 strings quoted in the cards (grep): " + "; ".join(f"{k}: {', '.join(v) if v else 'not found'}" for k, v in quoted.items()), "",
           "## The texts (verbatim)", "", "### public prompt (ConstructGap v1.0.1)", "```", base, "```", "",
           "### F5a-2 edit", "```", f"before: {F5A2_EDIT[0]!r}\nafter:  {F5A2_EDIT[1]!r}", "```", "",
           "### APPEND_M2", "```", APPEND_M2, "```", "",
           "### Tool sections (from data/moy2_line_inventory.json)", "```", f"TOOL_D (olm122 / olm124):\n{TOOL_D}", f"TOOL (olm119):\n{TOOL}", f"TOOL_U (olm125 / olm127, appended to TOOL_D):\n{TOOL_U}", "```", "",
           "### CUE", "```", repr(CUE), "```", ""]
    (CARDS / "PROMPT_PROVENANCE.md").write_text("\n".join(md), encoding="utf-8")
    for r in rows: print(f"{r[0]:<18} {r[2]:>5} {r[3]} {r[4]}")
    print("quoted:", quoted)
    print("mismatches:", bad)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
